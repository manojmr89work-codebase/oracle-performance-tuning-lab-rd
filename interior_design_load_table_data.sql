-- 2. Create Client Projects Master Table (Partitioned by Range on Customer ID)
-- Simulates high-volume enterprise projects segmented by customer tiers.
CREATE TABLE TAB_CLIENT_PROJECTS (
    project_id      NUMBER(12) GENERATED BY DEFAULT AS IDENTITY,
    customer_id     NUMBER(10) NOT NULL,
    client_name     VARCHAR2(100) NOT NULL,
    project_type    VARCHAR2(50) NOT NULL, -- 'RESIDENTIAL_FULL', 'COMMERCIAL_OFFICE', 'MODULAR_KITCHEN'
    project_status  VARCHAR2(20) NOT NULL, -- 'PLANNING', 'EXECUTION', 'COMPLETED'
    budget_amount   NUMBER(15, 2) NOT NULL,
    start_date      DATE NOT NULL,
    completion_date DATE,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT pk_TAB_CLIENT_PROJECTS PRIMARY KEY (project_id, customer_id)
)
PARTITION BY RANGE (customer_id) (
    PARTITION p_cust_tier1 VALUES LESS THAN (10000) 
        TABLESPACE users,
    PARTITION p_cust_tier2 VALUES LESS THAN (50000) 
        TABLESPACE users,
    PARTITION p_cust_tier3 VALUES LESS THAN (100000) 
        TABLESPACE users,
    PARTITION p_cust_enterprise VALUES LESS THAN (MAXVALUE) 
        TABLESPACE users
);

-- 3. Create Design Inventories Table (Materials, Hardware, Furniture & Finishes)
CREATE TABLE TAB_DESIGN_INVENTORIES (
    item_id         NUMBER(12) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_code        VARCHAR2(50) NOT NULL,
    item_name       VARCHAR2(150) NOT NULL,
    category        VARCHAR2(50) NOT NULL, -- 'WOODWORK', 'HARDWARE', 'FABRICS', 'LIGHTING', 'STONE'
    unit_price      NUMBER(12, 2) NOT NULL,
    stock_qty       NUMBER(10) NOT NULL,
    warehouse_code  VARCHAR2(20) NOT NULL,
    last_restock    DATE NOT NULL
);

-- 4. Create Inventory Allocations Table (Partitioned by Reference to Customer ID / Project)
-- Tracks material consumption per customer project across inventory items.
CREATE TABLE inventory_allocations (
    allocation_id   NUMBER(15) GENERATED BY DEFAULT AS IDENTITY,
    project_id      NUMBER(12) NOT NULL,
    customer_id     NUMBER(10) NOT NULL,
    item_id         NUMBER(12) NOT NULL,
    allocated_qty   NUMBER(10) NOT NULL,
    unit_cost       NUMBER(12, 2) NOT NULL,
    total_cost      NUMBER(15, 2) NOT NULL,
    order_date 		DATE NOT NULL,
    status          VARCHAR2(20) NOT NULL,
    CONSTRAINT pk_inv_allocations PRIMARY KEY (allocation_id, order_date, customer_id)
)
PARTITION BY RANGE (order_date)
INTERVAL (NUMTODSINTERVAL(1, 'DAY'))
SUBPARTITION BY RANGE (customer_id) (
    PARTITION p_alloc_base VALUES LESS THAN (TO_DATE('2014-01-01', 'YYYY-MM-DD')) (
        SUBPARTITION sp_base_tier1 VALUES LESS THAN (10000),
        SUBPARTITION sp_base_tier2 VALUES LESS THAN (50000),
        SUBPARTITION sp_base_tier3 VALUES LESS THAN (100000),
        SUBPARTITION sp_base_enterprise VALUES LESS THAN (MAXVALUE)
    )
);
